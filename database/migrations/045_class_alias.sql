-- Паралелката се чита по ИМЕТО ЗА ПРИКАЗ, а ознаката е внатрешна (сопственикот,
-- 26 септември 2026).
--
-- Ознаката (`school_classes.label`) е една за сите години и по неа се поврзува
-- сè: часовите, одделението на детето (како текст), распоредот. Затоа не смее
-- да се менува за да „изгледа убаво": преименување ја препишува и архивата.
-- Но тоа што луѓето го препознаваат е колоната „Одделение" од табелата на
-- училиштето — „Комбинирана II, III, IV", „V-б – ученици со пречки во
-- психичкиот развој" — и таа се менува од година во година.
--
-- ЗАТОА НА class_years, ПО ГОДИНА, како и описот (031): името за оваа година
-- не ја допира ланската. Го пишува само администраторот. САМО ЗА ПРИКАЗ —
-- ништо не го парсира и ништо не се поврзува по него; вредноста што се
-- зачувува насекаде останува ознаката.
--
-- Правилото за името, договорено истиот ден: римски број со големи букви,
-- цртичка, буква од кирилица (I-а, V-б); паралелките од иста генерација
-- по ред а, б, в; единствената без буква (VIII); комбинираната по
-- генерациите („Комбинирана II, III, IV"); подготвителната — „подготвителна".
-- Правилото е за луѓето што ги пишуваат имињата; базата не го проверува.
--
-- КОЛКУ ПАРАЛЕЛКИ ИМА ГОДИНАТА е факт од Годишната програма, не од базата:
-- базата брои колку се внесени, а ова кажува колку треба да има, за разликата
-- да се гледа наместо да се претпоставува.

ALTER TABLE class_years
  ADD COLUMN IF NOT EXISTS alias text;

COMMENT ON COLUMN class_years.alias IS
  'Име на паралелката за приказ во таа учебна година (колоната „Одделение“ од табелата на училиштето). Само за приказ — ништо не се поврзува по него; ознаката е внатрешна.';

ALTER TABLE school_years
  ADD COLUMN IF NOT EXISTS class_count integer;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conrelid = to_regclass('school_years') AND conname = 'school_years_class_count_check') THEN
    ALTER TABLE school_years
      ADD CONSTRAINT school_years_class_count_check CHECK (class_count IS NULL OR class_count BETWEEN 0 AND 200);
  END IF;
END $$;

COMMENT ON COLUMN school_years.class_count IS
  'Колку паралелки има годината според Годишната програма. Базата ги брои внесените; ова е со што се споредуваат.';
