-- Екстерен ученик нема одделение, интерен и интернатски имаат.
--
-- Досега тоа беше договор што го чуваа само внесувачите. Оваа проверка го
-- префрла врз базата, за да не може да се разиде тивко.
--
-- ЗОШТО САМО ЗА active. Архивските членства се тоа што миграцијата 018
-- постои да го зачува, па правилото не смее да пишува наназад во нив. Веќе
-- постои еден таков ред во 2026/2027 — internal, без одделение, active = false
-- — што е ученик тргнат од списокот. Кога некој ќе се врати на списокот,
-- active станува true и правилото почнува да важи за него.
--
-- DROP ... IF EXISTS пред ADD е намерно: проверката веќе беше додадена рачно
-- на домашната машина пред оваа датотека да постои, па без него миграцијата
-- таму би паднала со "constraint already exists".

ALTER TABLE student_enrollments
  DROP CONSTRAINT IF EXISTS kind_matches_grade;

ALTER TABLE student_enrollments
  ADD CONSTRAINT kind_matches_grade
  CHECK (
    NOT active
    OR (kind = 'external') = (grade IS NULL OR btrim(grade) = '')
  );
