-- Како училиштето ја формирало паралелката ОВАА ГОДИНА, со свои зборови:
-- „ученици со оштетен слух", „комбинирана паралелка", „мултихендикеп".
--
-- ЗОШТО НА class_years, А НЕ НА school_classes. Ознаката е глобална и се
-- повторува меѓу години: VIII-б е активно и во 2025/2026 и во 2026/2027 и
-- значи различно нешто во секоја, а 451 архивски час покажува кон истиот
-- class_id. Опис ставен на school_classes значи дека запишувањето на
-- овогодинешната вистина ја брише ланската — тивко, во табела од која читаат
-- архивските вкрстувања и печатените евидентни листови. Тоа е буквално
-- грешката со teachers.homeroom_class_id што миграцијата 016 мораше да ја
-- врати наназад.
--
-- САМО ЗА ПРИКАЗ. Ништо не го парсира, ниту еден упит не филтрира по него,
-- нема CHECK што го ограничува. Во моментот кога нешто ќе пресметува од оваа
-- колона, таа станала модел измислен пред да се знае правилото — а
-- сопственикот изречно рече дека правилото уште не му е јасно.
--
-- ОПСЕГОТ НА ГЕНЕРАЦИИ („III, IV, V") НАМЕРНО НЕ Е ТУКА. Тој се изведува од
-- student_enrollments.oddelenie, што е факт на самите деца и веќе има
-- сопственик (правило 5). Запишан и тука, би бил втор сопственик што може
-- тивко да се разиде — а веќе знаеме дека би се разидел: документот вели дека
-- II-б опфаќа II, III и IV, а децата во него се само II и III.
--
-- И НЕ СМЕЕ ДА СЕ НОСИ НАПРЕД СО КОПИРАЊЕ ГОДИНА. copyYearLessons денес не ја
-- допира оваа колона и не смее да почне: копијата е ланска работна верзија,
-- не доказ што е вистина оваа година — истото правило поради кое копирањето
-- престана да вметнува редови во teacher_years.

ALTER TABLE class_years
  ADD COLUMN IF NOT EXISTS description text;

COMMENT ON COLUMN class_years.description IS
  'Опис на паралелката за таа учебна година, со зборовите на училиштето. Само за приказ — ништо не го парсира. Опсегот на генерации не е тука: се изведува од student_enrollments.oddelenie.';
