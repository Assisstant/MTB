-- Наставните предмети по одделение, како што ги пропишува МОН/БРО за
-- 2026/2027. Референтни податоци, во истиот смисол во кој `bell_periods` се
-- референтни: нешто надвор од оваа куќа го одредува, ние го читаме.
--
-- ЗОШТО ТАБЕЛА, А НЕ ЛИСТА ВО КОДОТ. Истата причина поради која каталогот на
-- евидентниот лист се пресели од JavaScript литерал во редови: списокот се
-- менува по волја на министерството, а не по волја на програмерот, и мора да
-- може да се дополни без да се менува апликација.
--
-- ШТО НЕ Е ОВА. Не е сопственик на `lessons.subject`. Тоа поле останува
-- слободен текст и работната книга на училиштето и понатаму пишува во него
-- што ќе најде. Оваа табела е само ПОНУДА: што има смисла да се избере.
-- Час со предмет што го нема тука е сосема валиден час.
--
-- ПЛАНОТ НЕ СЕ ИЗВЕДУВА ОД ОПИСОТ НА ПАРАЛЕЛКАТА. Миграцијата 031 изречно
-- вели дека `class_years.description` е само за приказ и дека ништо не смее
-- да пресметува од неа. Затоа изборот се стеснува по ОДДЕЛЕНИЕ, никогаш по
-- план — сите планови се нудат заедно, обединети по име на предмет.

CREATE TABLE IF NOT EXISTS teaching_subjects (
    id           serial PRIMARY KEY,
    plan         text NOT NULL,
    category     text NOT NULL,
    subject      text NOT NULL,
    grade        text NOT NULL,
    weekly_hours integer,
    UNIQUE (plan, subject, grade)
);

CREATE INDEX IF NOT EXISTS teaching_subjects_grade_idx ON teaching_subjects (grade);

COMMENT ON TABLE teaching_subjects IS
  'МОН/БРО наставни предмети по план и одделение, 2026/2027. Референтна понуда за избор — НЕ е сопственик на lessons.subject.';

